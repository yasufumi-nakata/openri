def test_strictness_changes_p_value_tolerance():
    # t(30)=2.0 → actual p ≈ 0.0546. Reported p = 0.10 → diff ≈ 0.046.
    # lenient tolerance 0.05 → not flagged. strict tolerance 0.005 → flagged.
    text = """
Results
The marginal contrast was t(30) = 2.0, p = 0.10.
"""
    lenient = analyze_manuscript(RunRequest(manuscript_text=text, strictness="lenient"))
    strict = analyze_manuscript(RunRequest(manuscript_text=text, strictness="strict"))
    assert _by_id(lenient, "statistical_consistency").status == Status.PASSED
    assert _by_id(strict, "statistical_consistency").status == Status.FAILED


